// ============================================================
// COMMAND: tagall
// MEZUKA MD V5 - command/tagall.js
// ============================================================
module.exports = {
    name: "tagall",
    aliases: ["everyone", "all"],
    async execute({ conn, mek, m, from, sender, isOwner, isGroup, reply, botNumber, q, adhiqmini }) {
    try {
        if (!isGroup) return reply(`꒰ᵎ 📢 *Tag All* ᵎ꒱\n\n❌ This command can only be used in groups!\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        const groupMetadata = await conn.groupMetadata(from);
        const groupParticipants = groupMetadata.participants;
        const numOnly = (jid) => (jid || '').split('@')[0].split(':')[0];

        const senderMember = groupParticipants.find(p => numOnly(p.id) === numOnly(sender));
        const isSenderAdmin = senderMember?.admin === 'admin' || senderMember?.admin === 'superadmin';
        if (!isSenderAdmin && !isOwner) return reply(`꒰ᵎ 📢 *Tag All* ᵎ꒱\n\n❌ Only admins can use this command!\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        const mentions = groupParticipants.map(p => p.id);
        const mentionText = groupParticipants.map(p => `@${numOnly(p.id)}`).join(' ');
        const caption = q ? q : '📢 Attention everyone!';

        await conn.sendMessage(from, {
            text: `꒰ᵎ 📢 *Tag All* ᵎ꒱\n\n${caption}\n\n👥 *Members:* ${groupParticipants.length}\n\n${mentionText}\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`,
            mentions: mentions
        }, { quoted: adhiqmini });

        await m.react('📢');
    } catch (e) {
        reply(`꒰ᵎ ❌ *Error* ᵎ꒱\n\n⚠️ ${e.message}\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);
        console.log('TagAll Error:', e);
    }
    }
};
