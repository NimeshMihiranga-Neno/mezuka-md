// ============================================================
// COMMAND: groupdp
// MEZUKA MD V5 - command/groupdp.js
// ============================================================
module.exports = {
    name: "groupdp",
    aliases: ["setgroupdp", "setgcicon", "gpic"],
    async execute({ conn, mek, m, from, sender, isOwner, isGroup, reply, botNumber, quoted, adhiqmini }) {
    try {
        if (!isGroup) return reply(`꒰ᵎ 🖼️ *Group DP* ᵎ꒱\n\n❌ This command can only be used in groups!\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        const groupMetadata = await conn.groupMetadata(from);
        const groupParticipants = groupMetadata.participants;
        const numOnly = (jid) => (jid || '').split('@')[0].split(':')[0];

        let botMember = groupParticipants.find(p => numOnly(p.id) === numOnly(botNumber));
        if (!botMember && conn.user?.lid) {
            botMember = groupParticipants.find(p => numOnly(p.id) === numOnly(conn.user.lid));
        }
        const isBotAdmin = botMember?.admin === 'admin' || botMember?.admin === 'superadmin';
        if (!isBotAdmin) return reply(`꒰ᵎ 🖼️ *Group DP* ᵎ꒱\n\n⚠️ Bot is not an admin!\nPlease make the bot a group admin first.\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        const senderMember = groupParticipants.find(p => numOnly(p.id) === numOnly(sender));
        const isSenderAdmin = senderMember?.admin === 'admin' || senderMember?.admin === 'superadmin';
        if (!isSenderAdmin && !isOwner) return reply(`꒰ᵎ 🖼️ *Group DP* ᵎ꒱\n\n❌ Only admins can use this command!\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        // Must reply to or send an image
        const isImage = quoted?.type === 'imageMessage' || mek.message?.imageMessage;
        if (!isImage) return reply(`꒰ᵎ 🖼️ *Group DP* ᵎ꒱\n\n⚠️ Please send or reply to an image!\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);

        await m.react('⏳');

        let imgBuffer;
        if (quoted?.type === 'imageMessage') {
            imgBuffer = await quoted.download();
        } else {
            imgBuffer = await conn.downloadMediaMessage(mek);
        }

        await conn.updateProfilePicture(from, imgBuffer);

        await conn.sendMessage(from, {
            text: `꒰ᵎ 🖼️ *Group DP* ᵎ꒱\n\n✅ Group profile picture updated!\n\n👤 *Changed by:* @${numOnly(sender)}\n🏠 *Group:* ${groupMetadata.subject}\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`,
            mentions: [sender]
        }, { quoted: adhiqmini });

        await m.react('✅');
    } catch (e) {
        reply(`꒰ᵎ ❌ *Error* ᵎ꒱\n\n⚠️ ${e.message}\n\n　　˚₊‧꒰ა 🌸 ໒꒱‧₊˚\n*ᴍᴇᴢᴜᴋᴀ ᴍᴅ ᴠ4* 🖤 | *ʙʟᴀᴄᴋ ᴄᴀᴛ ᴏꜰᴄ*`);
        console.log('GroupDP Error:', e);
    }
    }
};
